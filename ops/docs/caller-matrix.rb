#!/usr/bin/env ruby
# Generates the caller matrix in docs/audiences-and-surfaces.md from the per-caller OpenAPI files, or checks it.
#
#   ruby ops/docs/caller-matrix.rb            # print the generated block
#   ruby ops/docs/caller-matrix.rb --write    # replace the block in the document
#   ruby ops/docs/caller-matrix.rb --check    # fail when the document or the per-caller files drifted
require 'yaml'

ROOT = File.expand_path('../..', __dir__)
OPENAPI = File.join(ROOT, 'contracts/openapi')
DOC = File.join(ROOT, 'docs/audiences-and-surfaces.md')
BEGIN_MARKER = '<!-- BEGIN GENERATED -->'
END_MARKER = '<!-- END GENERATED -->'

APP_TITLES = {
  'platform' => 'Platform', 'billing' => 'Billing', 'notification' => 'Notification',
  'mailroom' => 'Mailroom', 'survey' => 'Survey', 'attribution' => 'Attribution',
  'workflow' => 'Workflow', 'booking' => 'Booking', 'customer' => 'Customer', 'loyalty' => 'Loyalty'
}.freeze
APPS = APP_TITLES.keys.freeze

CALLERS = %w[tenant-user tenant-system platform-user customer-session public provider internal].freeze
PUBLIC_CONTAINERS = %w[customer-session public provider].freeze

def operations(file)
  document = YAML.load_file(file)
  found = {}
  document.fetch('paths', {}).each do |path, item|
    item.each do |method, operation|
      next unless operation.is_a?(Hash) && operation['operationId']

      found[[path, method]] = operation
    end
  end
  found
end

def prefix_of(path)
  return '/api/v1' if path == '/api/v1' || path.start_with?('/api/v1/')
  return '/system/v1' if path == '/system/v1' || path.start_with?('/system/v1/')
  return '/admin/v1' if path == '/admin/v1' || path.start_with?('/admin/v1/')
  return '/internal/v1' if path == '/internal/v1' || path.start_with?('/internal/v1/')
  return '/internal' if path.start_with?('/internal/')
  return "/public/#{path.split('/')[2]}" if path.start_with?('/public/')
  return '/oauth/token' if path == '/oauth/token'
  return '/.well-known/jwks.json' if path == '/.well-known/jwks.json'
  return '/p' if path == '/p' || path.start_with?('/p/')
  return '/t' if path == '/t' || path.start_with?('/t/')
  return '/go' if path == '/go' || path.start_with?('/go/')
  return '/hooks' if path == '/hooks' || path.start_with?('/hooks/')
  return '/portal' if path.start_with?('/portal/')
  return '/stripe/webhooks' if path.start_with?('/stripe/webhooks')

  "/#{path.split('/').reject(&:empty?).first}"
end

def container(app, caller)
  return 'platform' if app == 'platform'
  return "#{app}-public" if PUBLIC_CONTAINERS.include?(caller)

  "#{app}-api"
end

def per_caller_files
  files = {}
  CALLERS.each do |caller|
    Dir[File.join(OPENAPI, caller, '*.yaml')].sort.each do |file|
      app = File.basename(file, '.yaml')
      files[[caller, app]] = operations(file)
    end
  end
  files
end

def coverage_errors(files)
  errors = []
  files.each do |(caller, app), operations|
    operations.each do |key, operation|
      labels = Array(operation['x-allowed-callers'])
      unless labels.include?(caller)
        errors << "#{caller}/#{app}.yaml #{key.last.upcase} #{key.first} is labelled #{labels.inspect}, not #{caller}"
      end
      main = main_file(app)
      unless main.key?(key)
        errors << "#{caller}/#{app}.yaml #{key.last.upcase} #{key.first} is not in #{app}.yaml"
      end
    end
  end
  APPS.each do |app|
    main_file(app).each do |key, operation|
      Array(operation['x-allowed-callers']).each do |caller|
        next if files.fetch([caller, app], {}).key?(key)

        errors << "#{app}.yaml #{key.last.upcase} #{key.first} has caller #{caller}, but #{caller}/#{app}.yaml does not list it"
      end
    end
  end
  errors
end

MAIN_CACHE = {}
def main_file(app)
  MAIN_CACHE[app] ||= operations(File.join(OPENAPI, "#{app}.yaml"))
end

def block(files)
  rows = []
  APPS.each do |app|
    CALLERS.each do |caller|
      operations = files[[caller, app]]
      next if operations.nil? || operations.empty?

      prefixes = operations.keys.map { |path, _method| prefix_of(path) }.reject { |p| p.start_with?('/test-') }.uniq.sort
      shown = prefixes.empty? ? '-' : prefixes.map { |prefix| "`#{prefix}`" }.join(', ')
      rows << "| #{APP_TITLES[app]} | #{caller} | #{shown} | `#{container(app, caller)}` | #{operations.size} |"
    end
  end
  <<~BLOCK.chomp
    #{BEGIN_MARKER}
    <!-- Generated by ops/docs/caller-matrix.rb from contracts/openapi/<caller>/<app>.yaml. Run `make docs-check`. -->
    | App | Caller | Prefix | Container | Operations |
    |---|---|---|---|---|
    #{rows.join("\n")}
    #{END_MARKER}
  BLOCK
end

def fail_with(message)
  warn message
  exit 1
end

files = per_caller_files
errors = coverage_errors(files)
unless errors.empty?
  fail_with "The per-caller files do not match the contracts:\n  #{errors.uniq.join("\n  ")}"
end
generated = block(files)

case ARGV.first
when '--write'
  text = File.read(DOC)
  start = text.index(BEGIN_MARKER)
  stop = text.index(END_MARKER)
  fail_with "#{DOC} has no generated block" unless start && stop

  File.write(DOC, text[0...start] + generated + text[(stop + END_MARKER.length)..])
  puts "Wrote #{generated.lines.count { |line| line.start_with?('| ') && !line.start_with?('| App') && !line.start_with?('|---') }} rows to #{DOC}"
when '--check'
  fail_with "#{DOC} is missing" unless File.exist?(DOC)

  text = File.read(DOC)
  start = text.index(BEGIN_MARKER)
  stop = text.index(END_MARKER)
  fail_with "#{DOC} has no generated block" unless start && stop

  current = text[start...(stop + END_MARKER.length)]
  if current != generated
    fail_with "#{DOC} is out of date; run `ruby ops/docs/caller-matrix.rb --write`"
  end
  puts 'Caller matrix is current.'
else
  puts generated
end
