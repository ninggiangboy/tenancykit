package dev.ngb.attribution.links.domain.link;

import dev.ngb.core.error.BadRequestException;
import java.security.SecureRandom;
import java.util.Locale;
import java.util.regex.Pattern;

/**
 * A link's slug: the path segment a visitor follows, unique per tenant.
 *
 * <p>Three to sixty-four characters, lower case, starting with a letter or digit and continuing with letters, digits,
 * {@code _} or {@code -}. A generated slug is ten characters of an unambiguous base32 alphabet, so a person reading one
 * aloud cannot confuse {@code 0}/{@code o} or {@code 1}/{@code l}. The value is never a word, because a slug that read
 * as content would make a link look legitimate when it is not.
 */
public record Slug(String value) {

    public static final int MIN_LENGTH = 3;
    public static final int MAX_LENGTH = 64;
    public static final int GENERATED_LENGTH = 10;

    private static final Pattern VALID = Pattern.compile("^[a-z0-9][a-z0-9_-]{2,63}$");

    /** Crockford-style base32 without i, l, o and u, so a generated slug cannot be misread as a word. */
    private static final char[] ALPHABET = "0123456789abcdefghjkmnpqrstvwxyz".toCharArray();

    private static final SecureRandom RANDOM = new SecureRandom();

    public Slug {
        if (value == null || value.isBlank()) {
            throw new BadRequestException("A link slug is required.");
        }
        value = value.strip().toLowerCase(Locale.ROOT);
        if (!VALID.matcher(value).matches()) {
            throw new BadRequestException(
                    "A link slug is 3 to 64 characters of lower-case letters, digits, '_' or '-', starting with a"
                            + " letter or digit.");
        }
    }

    /** A slug the caller supplied, normalized and validated. */
    public static Slug of(String value) {
        return new Slug(value);
    }

    /** Ten characters of base32, regenerated by the caller on the rare collision. */
    public static Slug generate() {
        StringBuilder out = new StringBuilder(GENERATED_LENGTH);
        for (int index = 0; index < GENERATED_LENGTH; index++) {
            out.append(ALPHABET[RANDOM.nextInt(ALPHABET.length)]);
        }
        return new Slug(out.toString());
    }

    @Override
    public String toString() {
        return value;
    }
}
