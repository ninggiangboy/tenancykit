#!/usr/bin/env node
// Writes the operation-to-permission map from the OpenAPI documents, so a screen checks the same code the endpoint
// enforces instead of a copy typed by hand. Run by `pnpm --filter @suite/api-client generate`; CI compares the output.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parse } from 'yaml'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '../../../..')
const documents = {
  platform: 'contracts/openapi/platform.yaml',
  billing: 'contracts/openapi/billing.yaml',
}

const map = Object.fromEntries(
  Object.entries(documents).map(([api, path]) => {
    const document = parse(readFileSync(resolve(root, path), 'utf8'))
    const operations = {}
    for (const methods of Object.values(document.paths ?? {})) {
      for (const operation of Object.values(methods ?? {})) {
        const id = operation?.operationId
        const permission = operation?.['x-required-permission']
        if (id && permission) {
          if (operations[id] && operations[id] !== permission) {
            throw new Error(`${api}: operation ${id} appears twice with different permissions`)
          }
          operations[id] = permission
        }
      }
    }
    return [api, Object.fromEntries(Object.entries(operations).sort(([a], [b]) => a.localeCompare(b)))]
  }),
)

const file = resolve(here, '../src/generated/permissions.ts')
mkdirSync(dirname(file), { recursive: true })
writeFileSync(
  file,
  `// Generated by scripts/generate-permissions.mjs from contracts/openapi. Do not edit by hand.\n\nexport const permissions = ${JSON.stringify(map, null, 2)} as const\n\nexport type OperationPermission = (typeof permissions)['platform'][keyof (typeof permissions)['platform']]\n`,
)
console.log(`wrote ${Object.values(map).reduce((total, api) => total + Object.keys(api).length, 0)} operations`)
